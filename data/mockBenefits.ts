import type { Benefit, EligibilityRuleGroup } from "@/types/benefit";

/** Reusable eligibility rule fragments, composed per-benefit below. */
const ageBetween = (id: string, min: number, max: number, required = true) => ({
  id,
  field: "age",
  operator: "between" as const,
  value: [min, max],
  required,
});

const provinceIn = (id: string, provinces: string[], required = true) => ({
  id,
  field: "residence.province",
  operator: "in" as const,
  value: provinces,
  required,
});

const incomeLte = (id: string, max: number, required = true) => ({
  id,
  field: "annualHouseholdIncome",
  operator: "lte" as const,
  value: max,
  required,
});

const GYEONGGI = ["경기도", "서울특별시"];

function youthAgeGyeonggi(id: string): EligibilityRuleGroup {
  return {
    type: "all",
    rules: [ageBetween(`${id}-age`, 19, 34), provinceIn(`${id}-region`, GYEONGGI)],
  };
}

